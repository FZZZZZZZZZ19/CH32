/* ======================== 【为什么要有这个文件】 ========================  * 逐飞的 zf_driver_pit 只做一件事：让某个定时器按周期中断。它不提供  * 「隔 N 毫秒干一次」的调度。这个小模块补上那一层：中断里只做加法  * （g_app_tick_ms++），到点没到点的判断留给主循环的 app_tick_reached()。  *  * 为什么中断里只有一个 ++：中断里多花 1 微秒，主循环和别的中断就晚 1 微秒。  * 为什么用无符号减法比较时间：32 位毫秒数 49 天就回绕，  * (now - last) >= period 这种写法在回绕时结果依然正确。  * ====================================================================== */ 
 #include "app_config.h"
#include "app_tick.h"

volatile uint32 g_app_tick_ms = 0;

/*-------------------------------------------------------------------------------------------------------------------
 * 函数简介     启动系统节拍
 * 备注信息     TIM6 只做节拍，不能再拿去做 PWM 或别的 PIT
 *-----------------------------------------------------------------------------------------------------------------*/
void app_tick_init(void)
{
    g_app_tick_ms = 0;

    pit_ms_init(TIM6_PIT, APP_TICK_MS_PERIOD);      /* 1 ms */
    pit_enable(TIM6_PIT);
}

uint32 app_tick_get(void)
{
    return g_app_tick_ms;
}

/*-------------------------------------------------------------------------------------------------------------------
 * 函数简介     非阻塞周期判断
 * 参数说明     last_ms    静态变量地址，函数内部会更新它
 *              period_ms  周期（毫秒）
 * 返回参数     1 = 周期到了（并已更新 last_ms）；0 = 还没到
 * 备注信息     ★ 这里用"无符号减法"而不是 if(now >= last+period)：
 *              因为 g_app_tick_ms 会溢出回绕，用了减法即使回绕也能算对
 *              调用方式：
 *                  static uint32 t = 0;
 *                  if(app_tick_reached(&t, 500)) { ...每 500ms 执行一次... }
 *-----------------------------------------------------------------------------------------------------------------*/
uint8 app_tick_reached(uint32 *last_ms, uint32 period_ms)
{
    uint32 now = g_app_tick_ms;

    if((uint32)(now - *last_ms) >= period_ms)
    {
        *last_ms = now;
        return 1;
    }

    return 0;
}

/*-------------------------------------------------------------------------------------------------------------------
 * 函数简介     节拍中断服务（被 User/zf_isr.c 的 TIM6_IRQHandler 调用）
 * 备注信息     只加一个计数器，绝不做别的事
 *-----------------------------------------------------------------------------------------------------------------*/
void app_tick_irq(void)
{
    g_app_tick_ms ++;
}

